// Restores real transparency to a logo whose background is a uniform flat
// colour (the handover asset lost its alpha, or was matted flat in an
// earlier fix) — chroma-key removal with a soft, distance-based alpha
// falloff rather than a hard per-pixel threshold, so an anti-aliased edge
// fades out instead of leaving a jagged cutout.
//
// Usage: node scripts/remove-logo-background.mjs <input> <output> [--inner=N] [--outer=N]
// Background colour is sampled from the four corners (the median of the
// three closest of the four, in case one corner happens to touch the
// logo's own art) — every target file for this pass has a genuinely flat,
// uncontested corner, so this has been simple and reliable in practice, not
// dressed up as more robust than it is. Not run at build time: output is a
// committed file, regenerated by hand when a source asset changes.

import sharp from "sharp";

function parseArgs(argv) {
  const [input, output, ...rest] = argv;
  let inner = 12;
  let outer = 45;
  for (const arg of rest) {
    const innerMatch = /^--inner=(\d+)$/.exec(arg);
    const outerMatch = /^--outer=(\d+)$/.exec(arg);
    if (innerMatch) inner = Number(innerMatch[1]);
    if (outerMatch) outer = Number(outerMatch[1]);
  }
  if (!input || !output) {
    console.error("Usage: node scripts/remove-logo-background.mjs <input> <output> [--inner=N] [--outer=N]");
    process.exit(1);
  }
  return { input, output, inner, outer };
}

function colorDistance(r1, g1, b1, r2, g2, b2) {
  return Math.sqrt((r1 - r2) ** 2 + (g1 - g2) ** 2 + (b1 - b2) ** 2);
}

async function main() {
  const { input, output, inner, outer } = parseArgs(process.argv.slice(2));

  const { data, info } = await sharp(input).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width, height, channels } = info;

  const at = (x, y) => {
    const i = (y * width + x) * channels;
    return [data[i], data[i + 1], data[i + 2]];
  };
  const corners = [at(0, 0), at(width - 1, 0), at(0, height - 1), at(width - 1, height - 1)];
  // Median-of-four by summed pairwise distance: throws out the one corner
  // most likely to be sitting on the logo's own art, if any is.
  const sums = corners.map((c, i) => corners.reduce((s, other, j) => (i === j ? s : s + colorDistance(...c, ...other)), 0));
  const bg = corners[sums.indexOf(Math.min(...sums))];
  console.log(`sampled background: rgb(${bg[0]}, ${bg[1]}, ${bg[2]})`);

  for (let p = 0; p < width * height; p++) {
    const i = p * channels;
    const distance = colorDistance(data[i], data[i + 1], data[i + 2], bg[0], bg[1], bg[2]);
    const alpha = Math.max(0, Math.min(1, (distance - inner) / (outer - inner)));
    data[i + 3] = Math.round(data[i + 3] * alpha);
  }

  await sharp(data, { raw: { width, height, channels } }).png().toFile(output);
  console.log(`wrote ${output}`);
}

await main();
